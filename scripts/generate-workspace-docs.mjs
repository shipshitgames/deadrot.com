#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

const repoRoot = resolve(import.meta.dirname, "..");
const outputPath = resolve(repoRoot, "docs/repository-catalog.generated.md");
const check = process.argv.includes("--check");

function packageAt(path) {
  const manifest = JSON.parse(readFileSync(resolve(repoRoot, path, "package.json"), "utf8"));
  return { name: manifest.name ?? "(private app)", path };
}

function markdownTable(rows) {
  return [
    "| Workspace | Package |",
    "| --- | --- |",
    ...rows.map(({ path, name }) => `| \`${path}\` | \`${name}\` |`),
  ].join("\n");
}

const apps = ["apps/api", "apps/lore", "apps/web"].map(packageAt);
const games = [
  "apps/games/brawl",
  "apps/games/deadlane",
  "apps/games/pactfall",
  "apps/games/redline",
  "apps/games/rothulk",
  "apps/games/scourge-survivors",
  "apps/games/starblight",
  "apps/games/warline",
].map(packageAt);
const packages = ["packages/assets", "packages/catalog", "packages/game-kit", "packages/ui", "packages/warline"].map(
  packageAt,
);

const { GAME_APPS, LOBBY_SLUG, PLAYABLE_GAME_SLUGS } = await import(
  pathToFileURL(resolve(repoRoot, "packages/catalog/index.js")).href
);

if (PLAYABLE_GAME_SLUGS.length !== 7 || LOBBY_SLUG !== "warline") {
  throw new Error("Expected seven playable front games and Warline as the operation front.");
}

const workspaceGameSlugs = new Set(games.map(({ path }) => path.split("/").at(-1)));
for (const { slug } of GAME_APPS) {
  if (!workspaceGameSlugs.has(slug)) {
    throw new Error(`Catalog game ${slug} has no matching apps/games workspace.`);
  }
}

const roster = GAME_APPS.map((game) => {
  const architecture = game.slug === LOBBY_SLUG ? "Persistent Warline operation front" : "Playable front game";
  return `| ${game.title} | \`${game.slug}\` | ${architecture} | \`${game.status}\` |`;
}).join("\n");

const output = `<!-- GENERATED by scripts/generate-workspace-docs.mjs. Do not edit by hand. -->
# Repository catalog

This table is generated from the workspace manifests and \`@deadrot/catalog\`.
Regenerate with \`bun run docs:catalog\`; CI checks it with \`bun run docs:catalog:check\`.

## Apps

${markdownTable(apps)}

## Game architecture

Deadrot has seven playable front games plus **Warline**, the persistent shared
operation front. The catalog owns the roster, routes, ports, and deployment
records; this table deliberately follows its order rather than duplicating it.

| Game | Slug | Architecture role | Catalog status |
| --- | --- | --- | --- |
${roster}

## Runtime packages

${markdownTable(packages)}

## External studio dependencies

- \`@shipshitgames/engine\` is consumed as the published org-level engine; it is
  not a local package in this repository.
- \`packages/assetgen\` belongs to the sibling \`../shipshitgames\` studio repo.
  This repository owns the curated outputs and runtime asset packs, not the
  generator product.
`;

if (check) {
  const existing = readFileSync(outputPath, "utf8");
  if (existing !== output) {
    throw new Error("docs/repository-catalog.generated.md is stale; run bun run docs:catalog");
  }
} else {
  writeFileSync(outputPath, output);
}
